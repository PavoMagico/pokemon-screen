export const ALL_POKEMON_LIST = Object.keys(POKE_IDS).sort((a, b) => POKE_IDS[a] - POKE_IDS[b]);
export const KANTO = ALL_POKEMON_LIST.filter(p => POKE_IDS[p] <= 151);
export const JOHTO = ALL_POKEMON_LIST.filter(p => POKE_IDS[p] > 151 && POKE_IDS[p] <= 251);
export const HOENN = ALL_POKEMON_LIST.filter(p => POKE_IDS[p] > 251 && POKE_IDS[p] <= 386);

export const EVOLVED_NAMES = new Set(
  Object.entries(EVO_MAP).flatMap(([prev, evo]) => {
    const evos = Array.isArray(evo) ? evo : [evo];
    return evos
      .filter(e => POKE_IDS[prev] < POKE_IDS[e.next])
      .map(e => e.next);
  })
);

export const KANTO_BASE = KANTO.filter(p => !EVOLVED_NAMES.has(p) && !LEGENDARY.includes(p));
export const JOHTO_BASE = JOHTO.filter(p => !EVOLVED_NAMES.has(p) && !LEGENDARY.includes(p));
export const HOENN_BASE = HOENN.filter(p => !EVOLVED_NAMES.has(p) && !LEGENDARY.includes(p));
export const ALL_BASE = [...KANTO_BASE, ...JOHTO_BASE, ...HOENN_BASE];

export const getIconUri = (name: string) => {
  if (!name) return "";
  const id = POKE_IDS[name.toLowerCase()] || 158;
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-vii/icons/${id}.png`;
};

export const getAnimatedIconUri = (name: string, shiny: boolean = false) => {
  if (!name) return "";
  const lowerName = name.toLowerCase().replace(" ", "-");
  const mode = shiny ? "shiny" : "normal";
  return `https://img.pokemondb.net/sprites/black-white/anim/${mode}/${lowerName}.gif`;
};
